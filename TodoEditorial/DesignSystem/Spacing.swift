import SwiftUI

public enum AppSpacing {
    /// Zero corner radius - strictly brutalist
    public static let cornerRadius: CGFloat = 0
    
    /// Micro spacing: 4pt
    public static let xs: CGFloat = 4
    
    /// Small spacing: 8pt
    public static let sm: CGFloat = 8
    
    /// Medium standard spacing: 16pt
    public static let md: CGFloat = 16
    
    /// Large section spacing: 24pt
    public static let lg: CGFloat = 24
    
    /// Extra large spacing: 32pt
    public static let xl: CGFloat = 32
    
    /// Massive hero spacing: 48pt
    public static let xxl: CGFloat = 48
    
    /// Edge horizontal margin for poster layout
    public static let horizontalMargin: CGFloat = 18
    
    /// Hairline divider thickness
    public static let hairline: CGFloat = 1.0
    
    /// Bold stroke thickness
    public static let boldStroke: CGFloat = 2.0
}
